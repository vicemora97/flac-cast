const translations: Record<AppLanguage, Record<TranslationKey, string>> = { en, es };
let currentLanguage: AppLanguage = "en";

export function normalizeLanguage(value: string | null | undefined): AppLanguage {
  return value === "es" ? "es" : "en";
}

export function getLanguage(): AppLanguage {
  return currentLanguage;
}

export function setLanguage(language: AppLanguage): void {
  currentLanguage = language;
  localStorage.setItem("flac-cast-language", language);
  document.documentElement.lang = language;
  applyDocumentTranslations();
}

export function t(key: TranslationKey, variables: Record<string, string | number> = {}): string {
  return Object.entries(variables).reduce(
    (value, [name, replacement]) => value.replaceAll(`{${name}}`, String(replacement)),
    translations[currentLanguage][key]
  );
}

export function applyDocumentTranslations(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n as TranslationKey);
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-title]").forEach((element) => {
    element.title = t(element.dataset.i18nTitle as TranslationKey);
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-aria]").forEach((element) => {
    element.setAttribute("aria-label", t(element.dataset.i18nAria as TranslationKey));
  });
  root.querySelectorAll<HTMLInputElement>("[data-i18n-placeholder]").forEach((element) => {
    element.placeholder = t(element.dataset.i18nPlaceholder as TranslationKey);
  });
}
